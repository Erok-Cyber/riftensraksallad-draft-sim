const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'..');
const live=fs.readFileSync(path.join(root,'live.js'),'utf8');
const ctx={ownRoleMap:()=>({jungle:'Xin Zhao'}),buildPath:()=> 'Top → bot. Bot setup.',laneRead:()=>({top:{score:3},bot:{score:0}}),laneSetupScore:()=>0};
vm.createContext(ctx);vm.runInContext(live.slice(live.indexOf('function briefJunglePath(){'),live.indexOf('function renderMatchBrief(gp){')),ctx);
assert(ctx.briefJunglePath().startsWith('Top → bot.'));
ctx.buildPath=()=> 'Flexa clear mot mid-prio';assert(ctx.briefJunglePath().startsWith('Bot → top'));
ctx.laneRead=()=>({top:{score:0},bot:{score:3}});assert(ctx.briefJunglePath().startsWith('Top → bot'));
ctx.ownRoleMap=()=>({});assert(ctx.briefJunglePath().includes('låses'));
assert(live.includes("put('briefPath',briefJunglePath())"),'AI and local briefs both retain pathing');
assert(fs.readFileSync(path.join(root,'live.html'),'utf8').includes('id="briefPath"'));
const roles=['top','jungle','mid','adc','support'];
const ui={window:{RiftScouting:{lineup:()=>roles.map((role,i)=>({role,cmUsername:'Player'+i,roleConfidence:75}))}},Map,Set,Date};
vm.createContext(ui);vm.runInContext(fs.readFileSync(path.join(root,'rivals-history.js'),'utf8').replace('window.RiftRivals={mount};','window.RiftRivals={mount,orderedPicks,rows};'),ui);
const picks=[3,1,4,0,2].map(i=>({player:'Player'+i,champ:'Champ'+i}));
const sorted=ui.window.RiftRivals.orderedPicks(picks,{});
assert.equal(sorted.map(p=>p.role).join(','),roles.join(','));assert(sorted.every(p=>p.inferred));
assert.equal(picks[0].player,'Player3','do not mutate historical data');
const known=ui.window.RiftRivals.orderedPicks([{player:'Player0',champ:'X',role:'support'}],{});assert.equal(known[0].role,'support');assert.equal(known[0].inferred,false);
assert.equal(ui.window.RiftRivals.orderedPicks([{player:'Unknown',champ:'X'}],{})[0].role,'');
const html=ui.window.RiftRivals.rows({series:[{team:'<script>',games:[{number:1,picks}]}]},{});
assert(html.includes('TOP ≈'));assert(html.includes('historisk roll är inte bekräftad'));assert(!html.includes('<script>'));
console.log('PASS: early-brief path directions, no-jungle fallback, AI-safe display, top-to-support order, historical role precedence, unknown players and escaping.');
